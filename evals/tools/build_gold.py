def main() -> None:
    all_cases = AUDITED + NEW
    assert len(AUDITED) == 40, f"expected 40 audited, got {len(AUDITED)}"
    assert len(NEW) == 60, f"expected 60 new, got {len(NEW)}"
    assert len(all_cases) == 100

    GOLD.parent.mkdir(parents=True, exist_ok=True)
    with GOLD.open("w") as f:
        for c in all_cases:
            f.write(json.dumps(c) + "\n")

    needs_review = [c for c in all_cases if c["verification_status"] == "unverifiable"]
    with NEEDS_REVIEW.open("w") as f:
        for c in needs_review:
            f.write(json.dumps(c) + "\n")

    # ---- GOLD_REVIEW.md ----
    counts = {"verified": 0, "corrected": 0, "disputed": 0, "unverifiable": 0}
    for c in all_cases:
        counts[c["verification_status"]] += 1

    md = []
    md.append("# Gold Set Review — 100 cases\n")
    md.append("Built by `evals/tools/build_gold.py`. Each case is grounded in a CROSS ruling or unambiguous HTS text.\n")
    md.append(f"\n**Status counts:** verified={counts['verified']} · corrected={counts['corrected']} · "
              f"disputed={counts['disputed']} · unverifiable={counts['unverifiable']}\n")
    md.append(f"\n**Scored cases (excluded unverifiable):** {len(all_cases) - counts['unverifiable']}\n")
    md.append("\n## How to spot-check a citation\n")
    md.append("Each `CROSS:N...` or `CROSS:H...` ruling is fetchable at "
              "`https://rulings.cbp.gov/ruling/<NUMBER>`. The product description in the ruling "
              "should plausibly match the description in the gold case (CBP descriptions are more "
              "technical; we lightly reword into seller language).\n")
    md.append("\n## Audited cases (40)\n")
    md.append("\n| # | Description (truncated) | HTS-8 | Status | Source | Was |")
    md.append("\n|---|---|---|---|---|---|\n")
    for i, c in enumerate(AUDITED, 1):
        desc = c["description"][:70].replace("|", "\\|")
        prior = c.get("prior_expected_hts_8") or ""
        md.append(f"| {i} | {desc} | `{c['expected_hts_8']}` | {c['verification_status']} | {c['source']} | {prior} |\n")
    md.append("\n## New cases (60)\n")
    md.append("\n| # | Description (truncated) | HTS-8 | GRI | Source |")
    md.append("\n|---|---|---|---|---|\n")
    for i, c in enumerate(NEW, 1):
        desc = c["description"][:70].replace("|", "\\|")
        md.append(f"| N{i:02d} | {desc} | `{c['expected_hts_8']}` | {c['gri_rule']} | {c['source']} |\n")
    md.append("\n## Unverifiable cases (excluded from scoring)\n")
    for c in [x for x in all_cases if x["verification_status"] == "unverifiable"]:
        md.append(f"\n- **{c['id']}** — `{c['expected_hts_8']}` — {c['notes']}\n")

    REVIEW_MD.write_text("".join(md))

    print(f"Wrote {GOLD} ({len(all_cases)} cases)")
    print(f"Wrote {NEEDS_REVIEW} ({len(needs_review)} cases)")
    print(f"Wrote {REVIEW_MD}")
    print(f"Status counts: {counts}")


if __name__ == "__main__":
    main()
