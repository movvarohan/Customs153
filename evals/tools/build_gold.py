def case(id_, description, hts8, hts10, gri, source, notes,
         status="verified", accept_set=None, prior=None):
    obj = {
        "id": id_,
        "description": description,
        "expected_hts_8": hts8,
        "expected_hts_10": hts10,
        "gri_rule": gri,
        "source": source,
        "notes": notes,
        "verification_status": status,
    }
    if accept_set:
        obj["accept_set"] = accept_set
    if prior:
        obj["prior_expected_hts_8"] = prior
    return obj


